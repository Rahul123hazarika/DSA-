// To check whether the given number is divisible by 6 or not
import java.io.*;

class Divisible_by_six{
    public static void main (String[] args) {
        long n = 36358839596L;
 
        // finding given number is divisible by 6 or not
        if (n % 6 == 0)
              System.out.print("Yes");
        else
              System.out.print("No");
    }
}

